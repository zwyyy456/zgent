import { readFile, writeFile } from 'node:fs/promises';
import { isDeepStrictEqual } from 'node:util';
import { compile } from 'json-schema-to-typescript';

const read = async file => JSON.parse(await readFile(new URL(file, import.meta.url), 'utf8'));
const bundle = await read('../mcp-tools.json');
const api = await read('../control-api.openapi.json');
const defs = {};
const properties = {};
for (const tool of bundle.tools) {
  for (const side of ['input', 'output']) {
    const { $defs, $schema, ...schema } = tool[side + 'Schema'];
    for (const [name, definition] of Object.entries($defs)) {
      if (defs[name] && !isDeepStrictEqual(defs[name], definition)) {
        throw new Error('Conflicting common MCP definition: ' + name);
      }
      defs[name] = definition;
    }
    properties[tool.name + (side === 'input' ? 'Input' : 'Output')] = side === 'input' ? schema : {
      oneOf: schema.oneOf.map(branch => ({
        ...schema, oneOf: undefined, properties: { ...schema.properties, ...branch.properties },
      })),
    };
  }
}
for (const name of ['TaskList', 'TaskView', 'ProfileList', 'PendingRequestView', 'DecisionRequest', 'DecisionReceipt',
  'CancellationReceipt', 'CancelTaskCommand', 'TaskReviewReceipt', 'TaskReviewCommand', 'ArtifactSlice', 'Readiness', 'Problem']) {
  properties[name] = { $ref: '#/$defs/' + name };
}
for (const [name, definition] of Object.entries(api.components.schemas)) {
  defs[name] = JSON.parse(JSON.stringify(definition).replaceAll('#/components/schemas/', '#/$defs/'));
}
defs.JsonValue = { tsType: 'null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue }' };
const schema = { type: 'object', additionalProperties: false, properties, required: Object.keys(properties), $defs: defs };
// Conditional constraints are enforced by JSON Schema at runtime.
const typesSchema = JSON.parse(JSON.stringify(schema, (key, value) =>
  key === 'allOf' && Array.isArray(value) && value.every(branch => branch.if) ? undefined : value));
const result = await compile(typesSchema, 'Contracts', { bannerComment: '// Generated by scripts/generate.mjs from the versioned schemas.', unknownAny: true, strictIndexSignatures: true, maxItems: -1 });
const out = new URL('../src/types.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(out, 'utf8') !== result) throw new Error('Regenerate contracts with pnpm --filter @zgent/contracts build');
} else {
  await writeFile(out, result);
}
